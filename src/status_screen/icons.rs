//! The 1bpp icons of the status screen.
//!
//! The pixels come from `.tmp/screen.json`, the browser preview the layout was settled against,
//! and are stored in the byte layout `ImageRaw<BinaryColor>` uses. They are not handed to
//! `ImageRaw` though, see [`draw_bitmap`].

use embedded_graphics::pixelcolor::Rgb565;
use embedded_graphics::prelude::*;

/// A 1bpp icon.
///
/// The bytes are the layout `ImageRaw<BinaryColor>` uses: row major from the top left, most
/// significant bit first, each row padded to a whole number of bytes.
#[derive(Clone, Copy)]
pub(super) struct Bitmap {
    /// Width (px).
    pub(super) width: u32,
    /// Height (px).
    pub(super) height: u32,
    /// Pixels, one bit each.
    bytes: &'static [u8],
}

