/// Draws the set bits of `bitmap` in `color`, leaving the clear bits untouched, with the top left
/// corner of the bitmap at `origin`.
///
/// The bytes are in the layout `ImageRaw<BinaryColor>` reads, but `ImageRaw` cannot be used:
/// drawing an `Image` onto an `Rgb565` target goes through `From<BinaryColor> for Rgb565`, which
/// is `color.map_color(Self::BLACK, Self::WHITE)`
/// (`embedded-graphics-core-0.4.0/src/pixelcolor/conversion.rs:110-123`) and so can only produce
/// black and white. The icons need the orange of USB, the blue of Bluetooth and the gray of a
/// modifier that is not held, so the set bits are turned into pixels here and handed to
/// `draw_iter` in the wanted color. Clear bits produce no pixel at all, which also keeps the
/// background of whatever is already drawn.
pub(super) fn draw_bitmap<D: DrawTarget<Color = Rgb565>>(
    target: &mut D,
    bitmap: &Bitmap,
    origin: Point,
    color: Rgb565,
) {
    let stride = bitmap.width.div_ceil(8);
    let bytes = bitmap.bytes;
    let width = bitmap.width;
    let pixels = (0..bitmap.height).flat_map(move |y| {
        (0..width).filter_map(move |x| {
            let index = usize::try_from(y * stride + x / 8).ok()?;
            let byte = *bytes.get(index)?;
            if byte & (0x80_u8 >> (x % 8)) == 0 {
                return None;
            }
            let offset = Point::new(i32::try_from(x).ok()?, i32::try_from(y).ok()?);
            Some(Pixel(origin + offset, color))
        })
    });
    let _drawn = target.draw_iter(pixels);
}
